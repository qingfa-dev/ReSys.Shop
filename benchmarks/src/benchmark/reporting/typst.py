def write_latency_table(
    all_metrics: list[ModelMetrics],
    output_dir: Path = Path("outputs/tables"),
) -> Path:
    """Write ``latency.typ`` with p50/p95/p99 and throughput columns.

    Args:
        all_metrics: Results from ``BenchmarkRunner.run()``.
        output_dir: Destination directory.

    Returns:
        Path to the written ``.typ`` file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    ranked = rank_models(all_metrics, by="latency")

    col_headers = ["Model", "p50 (ms)", "p95 (ms)", "p99 (ms)", "Throughput (img/s)"]
    data_rows = []
    for m in ranked:
        lat = m.latency
        data_rows.append([
            m.model_name,
            _fmt(lat.get("p50_ms"), 1),
            _fmt(lat.get("p95_ms"), 1),
            _fmt(lat.get("p99_ms"), 1),
            _fmt(m.throughput_per_sec, 1),
        ])

    content = _AUTO_GEN_COMMENT + "\n" + _table_block(
        caption="Embedding Latency & Throughput — Fashion Retrieval Benchmark",
        label="tab:latency",
        col_headers=col_headers,
        data_rows=data_rows,
    )
    path = output_dir / "latency.typ"
    path.write_text(content, encoding="utf-8")
    logger.info("Typst latency table → %s", path)
    return path


def write_map_summary_table(
    all_metrics: list[ModelMetrics],
    output_dir: Path = Path("outputs/tables"),
) -> Path:
    """Write ``map_summary.typ`` — a compact ranked mAP overview table.

    Args:
        all_metrics: Results from ``BenchmarkRunner.run()``.
        output_dir: Destination directory.

    Returns:
        Path to the written ``.typ`` file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    ranked = rank_models(all_metrics, by="map")

    col_headers = ["Rank", "Model", "mAP"]
    data_rows = [
        [str(i + 1), m.model_name, _fmt(m.map_score)]
        for i, m in enumerate(ranked)
    ]

    content = _AUTO_GEN_COMMENT + "\n" + _table_block(
        caption="Model Ranking by Mean Average Precision — Fashion Retrieval Benchmark",
        label="tab:map-summary",
        col_headers=col_headers,
        data_rows=data_rows,
    )
    path = output_dir / "map_summary.typ"
    path.write_text(content, encoding="utf-8")
    logger.info("Typst mAP summary table → %s", path)
    return path


def write_thesis_tables(
    results: list[dict],
    output_dir: Path = Path("outputs/thesis/tables"),
) -> list[Path]:
    """Generate Typst tables from thesis benchmark results.

    Args:
        results: Output of ``ThesisRunner.run()`` — list of model result dicts.
        output_dir: Where to write ``.typ`` files.

    Returns:
        List of written file paths.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []

    # 1. Aggregate metrics table
    col_headers = ["Model", "mAP (mean ± SD)", "P@5", "P@10", "P@20", "R@5", "R@10", "R@20"]
    data_rows = []
    for r in results:
        agg = r.get("aggregate", {})
        map_mean = agg.get("map", {}).get("mean", 0.0)
        map_std = agg.get("map", {}).get("std", 0.0)
        row = [
            r["model_name"],
            f"{map_mean:.4f} ± {map_std:.4f}",
            _fmt(agg.get("precision@5", {}).get("mean")),
            _fmt(agg.get("precision@10", {}).get("mean")),
            _fmt(agg.get("precision@20", {}).get("mean")),
            _fmt(agg.get("recall@5", {}).get("mean")),
            _fmt(agg.get("recall@10", {}).get("mean")),
            _fmt(agg.get("recall@20", {}).get("mean")),
        ]
        data_rows.append(row)

    content = _AUTO_GEN_COMMENT + "\n" + _table_block(
        caption="Thesis Benchmark — Aggregate Retrieval Metrics (3-Fold CV)",
        label="tab:thesis-aggregate",
        col_headers=col_headers,
        data_rows=data_rows,
    )
    path = output_dir / "thesis_aggregate.typ"
    path.write_text(content, encoding="utf-8")
    paths.append(path)

    # 2. Efficiency table
    eff_headers = ["Model", "Latency (ms)", "Throughput (img/s)", "Load (ms)", "Storage (MB)", "RAM (MB)"]
    eff_rows = []
    for r in results:
        agg = r.get("aggregate", {})
        eff_rows.append([
            r["model_name"],
            f"{agg.get('latency_mean_ms', {}).get('mean', 0):.1f} ± {agg.get('latency_mean_ms', {}).get('std', 0):.1f}",
            f"{agg.get('throughput_per_sec', {}).get('mean', 0):.1f} ± {agg.get('throughput_per_sec', {}).get('std', 0):.1f}",
            f"{agg.get('load_time_ms', {}).get('mean', 0):.1f}",
            f"{agg.get('index_storage_mb', {}).get('mean', 0):.1f}",
            f"{agg.get('ram_mb', {}).get('mean', 0):.1f}",
        ])

    content = _AUTO_GEN_COMMENT + "\n" + _table_block(
        caption="Thesis Benchmark — Efficiency Metrics (3-Fold CV)",
        label="tab:thesis-efficiency",
        col_headers=eff_headers,
        data_rows=eff_rows,
    )
    path = output_dir / "thesis_efficiency.typ"
    path.write_text(content, encoding="utf-8")
    paths.append(path)

    logger.info("Thesis Typst tables → %s", output_dir)
    return paths


def write_all_tables(
    all_metrics: list[ModelMetrics],
    k_values: list[int] | None = None,
    output_dir: Path = Path("outputs/tables"),
) -> list[Path]:
    """Generate all five Typst table files.

    Returns:
        List of paths for precision, recall, ndcg, latency, map_summary.
    """
    return [
        write_precision_table(all_metrics, k_values, output_dir),
        write_recall_table(all_metrics, k_values, output_dir),
        write_ndcg_table(all_metrics, k_values, output_dir),
        write_latency_table(all_metrics, output_dir),
        write_map_summary_table(all_metrics, output_dir),
    ]
