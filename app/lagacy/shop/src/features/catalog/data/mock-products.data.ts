export function getProductById(id: string): Product | undefined {
  return mockProducts.find(p => p.id === id)
}

export function getProductBySlug(slug: string): Product | undefined {
  return mockProducts.find(p => p.slug === slug)
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return mockProducts.filter(p => p.category.slug === categorySlug)
}

export function getProductsInStock(): Product[] {
  return mockProducts.filter(p => p.inventory.quantity > 0)
}

export function getFeaturedProducts(): Product[] {
  return mockProducts.filter(p => p.compareAtPrice !== undefined)
}

export function getNewArrivals(limit = 8): Product[] {
  return [...mockProducts].sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()).slice(0, limit)
}

export function searchProducts(query: string, limit = 10): Product[] {
  const lowerQuery = query.toLowerCase()
  return mockProducts
    .filter(p => 
      p.name.toLowerCase().includes(lowerQuery) || 
      p.description.toLowerCase().includes(lowerQuery) ||
      p.tags.some(t => t.toLowerCase().includes(lowerQuery))
    )
    .slice(0, limit)
}